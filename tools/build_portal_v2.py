"""Builds portal-v2.html (LINK-style course cards + lesson sidebar) from portal.html.
Run after ANY change to portal.html:  python3 tools/build_portal_v2.py
Every patch asserts its anchor exists exactly once, so a portal.html change that breaks a patch fails loudly."""
import pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
src = (root/'portal.html').read_text(encoding='utf-8')

def patch(s, old, new):
    n = s.count(old)
    if n != 1:
        sys.exit('ANCHOR PROBLEM (%d matches): %s' % (n, old[:80]))
    return s.replace(old, new)

